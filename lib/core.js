"use strict";
// Updating MagicMirror itself: git pull + npm install, verified like every other change.
// The old node_modules folder is kept (renamed, so it costs no space or time) until the
// new version runs; otherwise git is reset and the old folder comes back.
const fs = require("node:fs");
const path = require("node:path");
const { run, readJSON } = require("./util");
const { UserError } = require("./errors");

class Core {
	constructor(mirror) {
		this.mirror = mirror;
		this.info = null; // result of the last check
	}

	git(args, timeout = 60000) {
		return run("git", args, { cwd: this.mirror.dir, timeout, env: { GIT_TERMINAL_PROMPT: "0" } });
	}

	// Looks for a newer MagicMirror on the branch the installation follows.
	async check() {
		if (!fs.existsSync(path.join(this.mirror.dir, ".git"))) {
			this.info = { checked: Date.now(), git: false };
			return this.info;
		}
		const fetch = await this.git(["fetch", "--quiet"]);
		if (fetch.code !== 0) {
			this.info = { checked: Date.now(), error: lastLine(fetch.out) };
			return this.info;
		}
		const count = await this.git(["rev-list", "--count", "HEAD..@{u}"]);
		const behind = count.code === 0 ? Number(count.out.trim()) || 0 : 0;
		let version = null;
		let node = null;
		if (behind > 0) {
			const pkg = await this.git(["show", "@{u}:package.json"]);
			try {
				const p = JSON.parse(pkg.out);
				version = p.version || null;
				node = p.engines && p.engines.node ? p.engines.node : null;
			} catch {
				// unknown package.json
			}
		}
		this.info = {
			checked: Date.now(),
			git: true,
			current: this.mirror.version(),
			behind,
			version,
			node,
			nodeOk: node ? satisfies(process.versions.node, node) : true,
			nodeVersion: process.versions.node,
			blocking: await this.localChanges()
		};
		return this.info;
	}

	// Tracked files changed by hand would make "git pull" fail. package-lock.json is
	// regenerated by npm anyway, so it doesn't count.
	async localChanges() {
		const st = await this.git(["status", "--porcelain", "--untracked-files=no"]);
		return st.out
			.split("\n")
			.map((l) => l.slice(3).trim())
			.filter((f) => f && f !== "package-lock.json");
	}

	steps() {
		return [
			{ key: "check", label: "check" },
			{ key: "backup", label: "backup" },
			{ key: "pull", label: "pull" },
			{ key: "deps", label: "deps" },
			{ key: "restart", label: "restart" },
			{ key: "verify", label: "verify" }
		];
	}

	async update(api, { restartAndVerify }) {
		const { step, log } = api;
		const dir = this.mirror.dir;
		step("check", "running");
		const info = await this.check();
		if (!info.git) throw new UserError("MagicMirror was not installed with git and can't be updated here");
		if (info.error) throw new UserError(`Can't reach the MagicMirror repository: ${info.error}`);
		if (!info.behind) {
			step("check", "done");
			return { status: "done", upToDate: true };
		}
		if (!info.nodeOk) throw new UserError(`MagicMirror ${info.version} needs Node.js ${info.node}, this system has ${info.nodeVersion}. Please update Node.js first.`);
		if (info.blocking.length) throw new UserError(`These MagicMirror files were changed by hand and block the update: ${info.blocking.join(", ")}`);
		step("check", "done", `${info.current} → ${info.version || "?"}`);

		step("backup", "running");
		const oldHead = (await this.git(["rev-parse", "HEAD"])).out.trim();
		const nm = path.join(dir, "node_modules");
		const nmBackup = path.join(dir, ".mmm-node_modules-backup");
		fs.rmSync(nmBackup, { recursive: true, force: true });
		if (fs.existsSync(nm)) fs.renameSync(nm, nmBackup);
		step("backup", "done");

		const restore = async (reason) => {
			log(`Restoring MagicMirror ${info.current}: ${reason}`);
			api.job.steps.push({ key: "rollback", label: "rollback", state: "running", detail: "" });
			await this.git(["reset", "--quiet", "--hard", oldHead]);
			fs.rmSync(nm, { recursive: true, force: true });
			if (fs.existsSync(nmBackup)) fs.renameSync(nmBackup, nm);
			const before = await this.mirror.snapshot();
			const r = await this.mirror.restart();
			const v = r.ok ? await this.mirror.verify(before) : { ok: false, reason: r.message };
			step("rollback", v.ok ? "done" : "failed", v.ok ? "" : v.reason);
			return { status: "rolledBack", reason };
		};

		step("pull", "running");
		await this.git(["checkout", "--quiet", "--", "package-lock.json"]);
		const pull = await this.git(["pull", "--ff-only"], 300000);
		if (pull.code !== 0) {
			step("pull", "failed", lastLine(pull.out));
			return restore(`git pull failed: ${lastLine(pull.out)}`);
		}
		step("pull", "done", `${info.current} → ${this.mirror.version()}`);

		step("deps", "running");
		const pkg = readJSON(path.join(dir, "package.json"), {});
		const args = pkg.scripts && pkg.scripts["install-mm"] ? ["run", "install-mm"] : ["install", "--omit=dev", "--no-audit", "--no-fund"];
		log(`npm ${args.join(" ")}`);
		const npm = await run("npm", args, { cwd: dir, timeout: 45 * 60000, onLine: log });
		if (npm.code !== 0) {
			step("deps", "failed", lastLine(npm.out));
			return restore(`npm install failed: ${lastLine(npm.out)}`);
		}
		step("deps", "done");

		const before = await this.mirror.snapshot();
		const outcome = await restartAndVerify(api, before);
		if (!outcome.ok) return restore(outcome.reason || "MagicMirror did not start");
		// the old modules folder is no longer needed; remove it in the background
		fs.rm(nmBackup, { recursive: true, force: true }, () => {});
		this.info = null;
		return { status: "done", from: info.current, to: this.mirror.version() };
	}
}

// Minimal semver range check for "engines" fields like ">=22.22.2 <23 || >=24".
function satisfies(version, range) {
	const v = parse(version);
	return range.split("||").some((part) =>
		part
			.trim()
			.split(/\s+/)
			.filter(Boolean)
			.every((cond) => {
				const m = /^(>=|<=|>|<|=|\^|~)?v?(\d+(?:\.\d+){0,2})/.exec(cond);
				if (!m) return true;
				const c = parse(m[2]);
				const cmp = compare(v, c);
				switch (m[1]) {
					case ">=": return cmp >= 0;
					case "<=": return cmp <= 0;
					case ">": return cmp > 0;
					case "<": return cmp < 0;
					case "^": return v[0] === c[0] && cmp >= 0;
					case "~": return v[0] === c[0] && v[1] === c[1] && cmp >= 0;
					default: return cmp === 0;
				}
			})
	);
}

function parse(v) {
	const p = String(v).replace(/^v/, "").split(".").map((x) => parseInt(x, 10) || 0);
	return [p[0] || 0, p[1] || 0, p[2] || 0];
}

function compare(a, b) {
	for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] - b[i];
	return 0;
}

function lastLine(text) {
	const lines = String(text || "").trim().split("\n").filter((l) => l.trim());
	return (lines.pop() || "").slice(0, 300);
}

module.exports = { Core, satisfies };
