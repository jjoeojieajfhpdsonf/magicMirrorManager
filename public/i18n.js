let LANG = "en";

function setLang(pref) {
	const auto = (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en";
	LANG = pref && I18N[pref] ? pref : auto;
	document.documentElement.lang = LANG;
}

function t(key, params = {}) {
	const s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
	return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined && params[k] !== null ? params[k] : ""));
}

function moduleLabel(name) {
	if (!name) return "?";
	const key = `mod.${name}`;
	if (I18N.en[key]) return t(key);
	return String(name).replace(/^MMM?-/, "");
}

function posLabel(pos) {
	return pos ? t(`pos.${pos}`) : t("pos.none");
}

function ago(ts) {
	if (!ts) return "";
	const s = (Date.now() - new Date(ts).getTime()) / 1000;
	if (s < 60) return t("time.now");
	if (s < 3600) return t("time.min", { n: Math.floor(s / 60) });
	if (s < 86400) return t("time.h", { n: Math.floor(s / 3600) });
	if (s < 86400 * 60) return t("time.d", { n: Math.floor(s / 86400) });
	if (s < 86400 * 730) return t("time.mo", { n: Math.floor(s / 86400 / 30) });
	return t("time.y", { n: Math.floor(s / 86400 / 365) });
}
